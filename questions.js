function mk(q, a, ds, ex) {
  const opts = [a];
  for (const d of ds) { if (opts.length >= 4) break; if (d !== undefined && d !== null && !opts.includes(d)) opts.push(d); }
  return { q, a, opts, ex };
}
function mkN(q, ans, cands, ex, fmt = N) {
  const ds = [];
  const pool = cands.concat([ans + 1, ans - 1, ans + 2, ans * 2, ans - 2, ans + 3, ans + 10]);
  for (const c of pool) { if (ds.length >= 3) break; if (Number.isFinite(c) && c !== ans && !ds.includes(c)) ds.push(c); }
  return mk(q, fmt(ans), ds.map(fmt), ex);
}
// 분수 보기 (값으로 중복 제거)
function mkF(q, [n, d], cands, ex) {
  const val = n / d, seen = [val], ds = [];
  for (const [cn, cd] of cands) { if (ds.length >= 3) break; const v = cn / cd; if (!cd || seen.some(s => Math.abs(s - v) < 1e-9)) continue; seen.push(v); ds.push(F(cn, cd)); }
  return mk(q, F(n, d), ds, ex);
}
