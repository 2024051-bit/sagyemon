const N = n => (n < 0 ? '−' + (-n) : '' + n);
function F(n, d) { // 기약분수 문자열
  if (d < 0) { n = -n; d = -d; }
  const g = gcd(n, d) || 1; n /= g; d /= g;
  if (d === 1) return N(n);
  return (n < 0 ? '−' : '') + `[${Math.abs(n)}|${d}]`;
}
function factorStr(n) {
  const out = []; let p = 2;
  while (n > 1 && p <= n) { let e = 0; while (n % p === 0) { n /= p; e++; } if (e) out.push(e > 1 ? `${p}^${e}` : `${p}`); p++; }
  return out.join(' × ') || '1';
}
// 단항식: c, [['x',2],['y',1]]
function mono(c, vs) {
  const v = vs.filter(([, e]) => e > 0).map(([l, e]) => e > 1 ? `${l}^${e}` : l).join('');
  if (c === 0) return '0';
  if (!v) return N(c);
  if (c === 1) return v;
  if (c === -1) return '−' + v;
  return N(c) + v;
}
// 다항식: [[c, vars]...]
function poly(terms) {
  let s = '';
  terms.forEach(([c, vs]) => {
    if (c === 0) return;
    const m = mono(Math.abs(c), vs);
    if (!s) s = (c < 0 ? '−' : '') + m;
    else s += (c < 0 ? ' − ' : ' + ') + m;
  });
  return s || '0';
}
